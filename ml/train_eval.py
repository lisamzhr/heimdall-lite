#!/usr/bin/env python3
"""Train on one CTU-13 scenario, test on another, and write metrics to reports/ml_results.md.
Usage: python ml/train_eval.py
"""
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import (average_precision_score, confusion_matrix,
                             f1_score, precision_score, recall_score)
from sklearn.model_selection import train_test_split

D = "data/ctu13/"
s42 = pd.read_parquet(D + "feat_42.parquet")
s44 = pd.read_parquet(D + "feat_44.parquet")
META = ["y", "src", "minute"]
ALL = [c for c in s42.columns if c not in META]
BEH = ["win_dst", "win_flows"]
NOBEH = [c for c in ALL if c not in BEH]
HOST_MIN = 10  # a host is "flagged" if >= 10 of its flows are predicted botnet


def fit(train, feats):
    m = RandomForestClassifier(n_estimators=100, max_depth=20, min_samples_leaf=2,
                               class_weight="balanced", n_jobs=-1, random_state=42)
    return m.fit(train[feats], train["y"])


def evaluate(m, test, feats):
    p = m.predict_proba(test[feats])[:, 1]
    yhat = (p >= 0.5).astype(int)
    y = test["y"].to_numpy()
    tn, fp, fn, tp = confusion_matrix(y, yhat, labels=[0, 1]).ravel()
    h = test.assign(pred=yhat).groupby("src").agg(inf=("y", "max"), n=("pred", "sum"))
    flagged = h["n"] >= HOST_MIN
    return {
        "precision": precision_score(y, yhat, zero_division=0),
        "recall": recall_score(y, yhat, zero_division=0),
        "f1": f1_score(y, yhat, zero_division=0),
        "fpr": fp / max(fp + tn, 1),
        "tp": int(tp), "fp": int(fp), "fn": int(fn), "tn": int(tn),
        "inf_hosts": int((h["inf"] == 1).sum()),
        "inf_flagged": int(((h["inf"] == 1) & flagged).sum()),
        "norm_hosts": int((h["inf"] == 0).sum()),
        "norm_flagged": int(((h["inf"] == 0) & flagged).sum()),
    }


runs = []


def run(name, train, test, feats):
    m = fit(train, feats)
    r = evaluate(m, test, feats)
    r.update(run=name, features=len(feats))
    runs.append(r)
    return m


mA = run("train 42 -> test 44", s42, s44, ALL)
run("train 42 -> test 44 (no behaviour feats)", s42, s44, NOBEH)
run("train 44 -> test 42", s44, s42, ALL)
run("train 44 -> test 42 (no behaviour feats)", s44, s42, NOBEH)
tr, te = train_test_split(s44, test_size=0.3, random_state=42, stratify=s44["y"])
run("random 70/30 split inside 44 (optimistic)", tr, te, ALL)

cols = ["run", "features", "precision", "recall", "f1", "fpr", "tp", "fp", "fn", "tn",
        "inf_flagged", "inf_hosts", "norm_flagged", "norm_hosts"]
df = pd.DataFrame(runs)[cols]
for c in ["precision", "recall", "f1", "fpr"]:
    df[c] = df[c].map("{:.3f}".format)
lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
for _, r in df.iterrows():
    lines.append("| " + " | ".join(str(r[c]) for c in cols) + " |")
with open("reports/ml_results.md", "w") as f:
    f.write("# ML results (generated by ml/train_eval.py)\n\n" + "\n".join(lines) + "\n")
print("\n".join(lines))

imp = pd.Series(mA.feature_importances_, index=ALL).sort_values()
plt.figure(figsize=(6, 5))
imp.plot.barh()
plt.title("Feature importance (train 42 -> test 44)")
plt.tight_layout()
plt.savefig("reports/img/ml-feature-importance.png", dpi=120)
print(imp.sort_values(ascending=False).head(8).round(3).to_string())
